import { test, expect } from "@playwright/test";
import { calculateTax, summarizeTax } from "../../lib/compliance-tax";

test("monthly totals, numbered records and readable history agree with the export", async ({ page }) => {
  const lease = calculateTax({ kind: "LEASE", reference: "2026-001", date: "2026-10-01", customer: "Sample buyer", vehicle: "Sample vehicle", vehicleValue: "10000", contractTax: "787.50", garageAddress: "Verified address", localTaxes: [{ code: "CITY", rate: "1" }], qualified: true, localConfirmed: true });
  const sale = calculateTax({ ...lease.input, kind: "SALE", reference: "2026-002", vehicleValue: "20000" });
  const records = [lease, sale].map((snapshot, index) => ({ id: `sample-${index}`, reference: snapshot.input.reference, kind: snapshot.input.kind, snapshot, status: "ACTIVE", version: 1 }));
  const history = [1, 2].map(index => ({ id: `event-${index}`, action: "SAVE", actorId: "internal-opaque-staff-id", actorName: "Sample Manager", createdAt: "2026-10-01T18:00:00Z", details: { before: index === 1 ? records[0] : null, after: records[0] } }));
  await page.route("**/api/compliance/tax?*", route => route.fulfill({ json: { month: "2026-10", period: null, records, history, summary: summarizeTax(records), revision: "sample-revision" } }));
  await page.goto("/login");
  await page.getByLabel("Email").fill("morgan.manager@local.test");
  await page.getByLabel("Password", { exact: true }).fill("dispatch123!");
  const signedIn = page.waitForResponse(response => response.url().endsWith("/api/auth/login"));
  await page.getByRole("button", { name: "Sign in" }).click();
  expect((await signedIn).ok()).toBe(true);
  await page.goto("/compliance");
  await expect(page.getByText("Loading tax records…", { exact: true })).toBeHidden();
  await expect(page.getByText("Adjustments · rebates, residual, trade-in and finance charges (if applicable)")).toBeVisible();
  await expect(page.getByLabel("Manufacturer rebates ($)", { exact: true })).toBeHidden();
  await page.getByRole("button", { name: "Monthly worksheet", exact: true }).click();
  await expect(page.getByText("Combined recorded taxable amounts: $30,000.00", { exact: true })).toBeVisible();
  const totals = page.getByRole("region", { name: "Monthly totals" });
  await expect(totals).toContainText("Vehicles sold: 1");
  await expect(totals).toContainText("Vehicles leased: 1");
  await expect(totals).toContainText("Total taxable lease amount: $10,000.00");
  await expect(totals).toContainText("Upfront lease tax (state + local): $787.50");
  await expect(page.getByText("#1 · 2026-001 · Lease · Recorded", { exact: true })).toBeVisible();
  const downloaded = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download CSV", exact: true }).click();
  const stream = await (await downloaded).createReadStream();
  let csv = "";
  for await (const chunk of stream!) csv += chunk.toString();
  expect(csv).toContain("10000.00");
  expect(csv).toContain("787.50");
  expect(csv).toContain("20000.00");
  await page.getByRole("button", { name: "History", exact: true }).click();
  await expect(page.getByText(/Activity 1 · Contract corrected · 2026-001 · Sample Manager/)).toBeVisible();
  await expect(page.getByText("internal-opaque-staff-id")).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.locator("main").last().evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
});
