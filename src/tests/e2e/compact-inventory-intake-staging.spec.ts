import { readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";
import { assertLaborStagingTarget } from "../../../scripts/lib/labor-staging-target.mjs";
import { explainSyntheticWorkdayDelay } from "./helpers/synthetic-workday";

test.setTimeout(120_000);
test.beforeAll(() => {
  if (process.env.LABOR_STAGING_CONFIRM !== "isolated" || process.env.PLAYWRIGHT_BASE_URL !== "http://127.0.0.1:3200") throw new Error("Use isolated local staging only.");
  assertLaborStagingTarget(process.env.DATABASE_URL ?? "");
});

test("compact intake saves real linked records on one page, recovers retries and keeps adoption optional", async ({ page, request }) => {
  const fixture = JSON.parse(readFileSync("test-results/labor-staging/compact-intake-browser-fixture.json", "utf8")) as { vehicleId: string; vin: string; locationId: string; ownerUserId: string };
  expect((await request.get(`/api/inventory-units/compact-intake?vehicleId=${fixture.vehicleId}`)).status()).toBe(401);
  expect((await page.request.post("/api/auth/login", { data: { email: "morgan.manager@local.test", password: "dispatch123!" } })).ok()).toBe(true);
  await explainSyntheticWorkdayDelay(page, "/prototype/inventory-intake", "Isolated synthetic compact intake acceptance; not a real workday.");
  const here = `/prototype/inventory-intake?vehicleId=${fixture.vehicleId}`;
  await page.goto("/vehicles/recon-repair-advisor");
  await page.locator('input[name="search"]').fill(fixture.vin);
  await page.getByRole("button", { name: "Find work", exact: true }).click();
  await expect(page).toHaveURL(`/prototype/inventory-intake?vehicleId=${fixture.vehicleId}&advisor=1`);
  await expect(page.getByRole("heading", { name: "Vehicle intake · start work", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Save & Open Planning", exact: true })).toBeVisible();
  await expect(page.getByLabel("VIN", { exact: true })).toHaveValue(fixture.vin);
  await page.goto(here);
  await expect(page.getByRole("heading", { name: "Inventory intake", exact: true })).toBeVisible();
  await expect(page.getByText("New form · Review before adoption", { exact: true })).toBeVisible();
  await expect(page.getByLabel("VIN", { exact: true })).toHaveValue(fixture.vin);
  await page.locator('[name="odometer"]').fill("56100");
  await page.locator('[name="source"]').selectOption("AUCTION");
  await page.locator('[name="acquiredOn"]').fill("2026-10-17");
  await page.locator('[name="seller"]').fill("Synthetic auction seller");
  await page.locator('[name="purchaseAmount"]').fill("12500");
  await page.locator('[name="priceStatus"]').selectOption("INCURRED");
  await page.locator('[name="reference"]').fill(`SYNTHETIC-${fixture.vehicleId}`);
  await page.locator('[name="location"]').selectOption(fixture.locationId);
  await page.locator('[name="staff"]').selectOption(fixture.ownerUserId);
  await page.locator('[name="whereabouts"]').fill("Synthetic receiving lane");
  await page.locator('[name="condition"]').fill("Synthetic intake inspection; right fender damage.");
  await page.locator('[name="concern"]').fill("Synthetic inspect front brakes before recon planning.");
  await page.locator('[name="pendingNotes"]').fill("Synthetic acquisition owner will verify title, keys and document references.");
  await page.getByLabel("I confirm dealership ownership or consignment authority.", { exact: true }).check();
  await page.setViewportSize({ width: 1440, height: 1000 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/labor-staging/compact-intake-desktop.png", fullPage: true });
  let lostReceipt: { inventoryUnitId: string; inventoryNumber: string; intakeVersion: number; unitVersion: number } | undefined;
  let originalKey: string | undefined;
  await page.route("**/api/inventory-units/compact-intake", async route => {
    if (route.request().method() !== "POST") return route.continue();
    const body = route.request().postDataJSON();
    if (!lostReceipt) {
      originalKey = body.idempotencyKey;
      const response = await route.fetch();
      expect(response.ok()).toBe(true);
      lostReceipt = (await response.json()).result;
      await route.abort("failed");
    } else {
      expect(body.idempotencyKey).toBe(originalKey);
      await route.continue();
    }
  });
  await page.getByRole("button", { name: "Save Inventory", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: /fetch|interrupted|network/i })).toBeVisible();
  await page.getByRole("button", { name: "Save Inventory", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Inventory saved and linked" })).toBeVisible();
  await page.unroute("**/api/inventory-units/compact-intake");
  const stored = await (await page.request.get(`/api/inventory-units/compact-intake?vehicleId=${fixture.vehicleId}`)).json();
  expect(stored.intakeVersion).toBe(lostReceipt?.intakeVersion);
  expect(stored.unitVersion).toBe(lostReceipt?.unitVersion);
  expect(stored.details.purchaseCents).toBe(1_250_000);
  const inventoryRoute = await page.request.get(`/vehicles/recon-repair-advisor/find-work?search=${fixture.vin}`, { maxRedirects: 0 });
  expect([200, 307]).toContain(inventoryRoute.status());
  const inventoryDestination = `/vehicles/${fixture.vehicleId}/inventory-planning`;
  if (inventoryRoute.status() === 307) expect(inventoryRoute.headers().location).toBe(inventoryDestination);
  else expect(await inventoryRoute.text()).toContain(inventoryDestination);
  expect(lostReceipt?.inventoryNumber).toBe(fixture.vin.slice(-6));
  await page.getByText("Correct inventory number · authorized staff", { exact: true }).click();
  const correctedNumber = `FIX-${fixture.vehicleId.slice(-8).toUpperCase()}`;
  await page.getByLabel("Corrected inventory number", { exact: true }).fill(correctedNumber);
  await page.getByLabel("Correction reason", { exact: true }).fill("Synthetic authorized inventory number correction.");
  await page.getByRole("button", { name: "Save number correction", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Inventory number corrected" })).toBeVisible();
  const corrected = await (await page.request.get(`/api/inventory-units/compact-intake?vehicleId=${fixture.vehicleId}`)).json();
  expect(corrected.inventoryUnitId).toBe(lostReceipt?.inventoryUnitId);
  expect(corrected.inventoryNumber).toBe(correctedNumber);
  expect(corrected.unitVersion).toBe(stored.unitVersion + 1);
  expect(corrected.details.purchaseCents).toBe(1_250_000);
  await expect(page).toHaveURL(here);
  const responsePromise = page.waitForResponse(response => response.url().endsWith("/api/inventory-units/compact-intake") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Save & Start Repair Order", exact: true }).click();
  const saved = await (await responsePromise).json();
  expect(saved.result.inventoryUnitId).toBe(lostReceipt?.inventoryUnitId);
  expect(saved.result.repairOrderId).toBeTruthy();
  expect(saved.result.inventoryNumber).toBe(correctedNumber);
  await expect(page.getByRole("link", { name: "Build estimate in Labor Guide", exact: true })).toHaveAttribute("href", `/prototype/repair-explorer?repairOrderId=${saved.result.repairOrderId}`);
  await expect(page).toHaveURL(here);
  await page.locator('[name="seller"]').fill("Unsaved synthetic seller correction");
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("link", { name: "Build estimate in Labor Guide", exact: true }).click();
  await expect(page).toHaveURL(here);
  await expect(page.locator('[name="seller"]')).toHaveValue("Unsaved synthetic seller correction");
  await page.getByRole("button", { name: "Save Inventory", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Inventory saved and linked" })).toBeVisible();
  await page.getByRole("radio", { name: "Prepare for Sale", exact: true }).check();
  await expect(page.getByRole("button", { name: "Save & Open Selling Workbench", exact: true })).toBeVisible();
  await page.getByRole("radio", { name: "Customer Repair", exact: true }).check();
  await expect(page.getByRole("button", { name: "Save Inventory", exact: true })).toHaveCount(0);
  await expect(page.getByRole("link", { name: "Open customer check-in", exact: true })).toHaveAttribute("href", `/vehicles/repair-orders?intakeSource=WALK_IN&vehicleId=${fixture.vehicleId}`);
  await page.getByRole("radio", { name: "Dealership Repair / Recon", exact: true }).check();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/labor-staging/compact-intake-mobile.png", fullPage: true });
  await page.goto(`/vehicles/repair-orders?intakeSource=INVENTORY_RECON&vehicleId=${fixture.vehicleId}`);
  await expect(page.getByRole("heading", { name: "Check In Vehicle", exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Try compact intake · New form for review", exact: true })).toBeVisible();
  await page.goto(`/vehicles/${fixture.vehicleId}/intake`);
  await page.getByLabel("Seller / acquired from", { exact: true }).fill("");
  await page.getByLabel("Purchase invoice / reference (optional)", { exact: true }).fill("");
  await page.getByLabel("Documents received / references (optional)", { exact: true }).fill("");
  await page.getByLabel("Pending information / follow-up plan (optional)", { exact: true }).fill("");
  await expect(page.getByLabel("Record / revision reason (required)", { exact: true })).toHaveCount(0);
  const confirm = page.locator("footer").getByRole("button", { name: "Confirm intake & open vehicle details", exact: true });
  await page.locator("footer").getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.locator("footer").getByRole("status")).toContainText("Intake draft saved");
  await expect(page.locator("header").getByRole("status")).toContainText("Intake draft");
  await page.route(`**/api/vehicles/${fixture.vehicleId}/intake`, route => route.fulfill({ status: 403, contentType: "application/json", body: JSON.stringify({ error: "Synthetic permission denial for retry acceptance." }) }), { times: 1 });
  await confirm.click();
  await expect(page.locator("footer").getByRole("alert")).toContainText("Synthetic permission denial");
  await page.screenshot({ path: "test-results/labor-staging/existing-intake-action-feedback.png", fullPage: true });
  await expect(page.getByLabel("Odometer", { exact: true })).toHaveValue("56100");
  await confirm.click();
  await expect(page).toHaveURL(`/vehicles/${fixture.vehicleId}/details`);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/vehicles/recon-repair-advisor");
  await page.screenshot({ path: "test-results/labor-staging/advisor-execution-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/labor-staging/advisor-execution-mobile.png", fullPage: true });
  await page.locator('input[name="search"]').fill(fixture.vin);
  await page.getByRole("button", { name: "Find work", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/vehicles/shop-planning\\?repairOrderId=${saved.result.repairOrderId}&`));
  await expect(page.getByText("Repair planning unavailable", { exact: true })).toHaveCount(0);
  await page.goto(`/prototype/inventory-intake?vehicleId=${fixture.vehicleId}&advisor=1`);
  await page.locator('[name="concern"]').fill("Synthetic advisor planning handoff, reuse existing repair order.");
  await page.getByRole("button", { name: "Save & Open Planning", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/vehicles/shop-planning\\?repairOrderId=${saved.result.repairOrderId}&`));
  await page.goto("/prototype/repair-workflow");
  await page.getByRole("searchbox").fill(fixture.vin);
  await page.getByRole("button", { name: "Find work", exact: true }).click();
  await expect(page).toHaveURL(`/prototype/repair-workbench?repairOrderId=${saved.result.repairOrderId}`);
  await expect(page.getByRole("heading", { name: "Repair Workbench", exact: true })).toBeVisible();
  await expect(page.locator('nav[aria-label="Repair workflow"] a')).toHaveCount(9);
  await expect(page.locator('[data-repair-workflow-tool] details[id^="repair-planning-step-"]')).toHaveCount(1);
  await page.screenshot({ path: "test-results/labor-staging/repair-workflow-mobile.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  for (const label of ["3. Estimate", "4. Authorize", "5. Parts & release", "6. Assign", "7. Repair", "8. Quality check", "9. Closeout / handoff"]) {
    await page.getByRole("link", { name: new RegExp("^" + label) }).click();
    await expect(page.locator("[data-repair-workflow-tool]")).not.toContainText("This tool could not load");
  }
  await expect(page.getByRole("button", { name: "Close repair & record handoff", exact: true })).toBeVisible();
  await expect(page.getByRole("checkbox", { name: "Keys verified", exact: true })).not.toBeChecked();
  await page.screenshot({ path: "test-results/labor-staging/repair-workflow-handoff.png", fullPage: true });
  await page.getByRole("link", { name: /^3\. Estimate/ }).click();
  await page.getByRole("link", { name: "Build estimate in simplified Labor Guide", exact: true }).click();
  await expect(page).toHaveURL(`/prototype/repair-explorer?repairOrderId=${saved.result.repairOrderId}&workflow=review`);
  await expect(page.getByText("2019 Ford F-150", { exact: false })).toHaveCount(0);
});
