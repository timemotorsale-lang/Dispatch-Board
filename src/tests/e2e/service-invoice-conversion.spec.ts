import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import { assertLaborStagingTarget } from "../../../scripts/lib/labor-staging-target.mjs";
import { explainSyntheticWorkdayDelay } from "./helpers/synthetic-workday";

test.use({ actionTimeout: 15_000 });

test("Labor Guide reviews and issues the approved estimate once before payment", async ({ page }) => {
  test.setTimeout(150_000);
  if (process.env.LABOR_STAGING_CONFIRM !== "isolated") throw new Error("Use the isolated labor staging database.");
  assertLaborStagingTarget(process.env.DATABASE_URL ?? "");
  const fixture = JSON.parse(readFileSync("test-results/labor-staging/invoice-conversion-fixture.json", "utf-8"));
  const billingUrl = `/api/repair-orders/${fixture.repairOrderId}/billing`;
  const readBilling = async () => (await page.request.get(billingUrl)).json();
  async function correctEstimateCustomer(name: string) {
    const { readiness } = await readBilling();
    expect(readiness.estimateId).toBe(fixture.estimateId);
    const correction = await page.request.post(`/api/repair-orders/${fixture.repairOrderId}/document-review`, {
      data: { action: "CUSTOMER_DETAILS", ...readiness.estimateDocument, customer: { name, phone: "", email: "", address: "" }, idempotencyKey: randomUUID() },
    });
    expect(correction.ok(), await correction.text()).toBe(true);
    const updated = (await readBilling()).readiness;
    expect(updated.estimateId).toBe(fixture.estimateId);
    expect(updated.estimateDocument.documentId).not.toBe(readiness.estimateDocument.documentId);
    expect(updated.estimateDocument.documentHash).not.toBe(readiness.estimateDocument.documentHash);
    return updated.estimateDocument;
  }
  async function rejectStaleReview(button: string) {
    const rejected = page.waitForResponse(response => response.url().endsWith(billingUrl) && response.request().method() === "POST");
    await page.getByRole("button", { name: button, exact: true }).click();
    expect((await rejected).status()).toBe(409);
    await expect(page.getByRole("alert").filter({ hasText: "The saved estimate document changed." })).toBeVisible();
    await expect(page.getByRole("button", { name: "Issue invoice", exact: true })).toHaveCount(0);
    expect((await readBilling()).invoices).toEqual([]);
    await page.getByRole("link", { name: "Review latest estimate document" }).click();
  }
  const login = await page.request.post("/api/auth/login", { data: { email: "morgan.manager@local.test", password: "dispatch123!" } });
  expect(login.ok()).toBe(true);
  await explainSyntheticWorkdayDelay(page, "/vehicles/service-billing", "Synthetic invoice conversion verification.");
  await page.goto(`/vehicles/repair-workbench?repairOrderId=${fixture.repairOrderId}&step=handoff`);
  await page.locator("summary").filter({ hasText: "Tools ⋮" }).click();
  const tools = page.getByRole("navigation", { name: "Repair order tools" });
  const billingHref = await tools.getByRole("link", { name: "Billing & receipts", exact: true }).getAttribute("href");
  await page.goto(billingHref!);
  await expect(page.getByRole("heading", { name: "Service Billing" })).toBeVisible({ timeout: 20_000 });
  await expect(page.getByText(/older package needs to be refreshed/)).toBeVisible({ timeout: 20_000 });
  const handoff = `/vehicles/repair-workbench?repairOrderId=${fixture.repairOrderId}&step=handoff`;
  await page.goto(handoff);
  await page.locator("summary").filter({ hasText: "Tools ⋮" }).click();
  const invoiceHref = await tools.getByRole("link", { name: "Review / print invoice" }).getAttribute("href");
  await page.goto(invoiceHref!);
  await expect(page).toHaveURL(/\/diagnostics\/labor-guide\?/);
  expect(new URL(page.url()).searchParams.get("returnTo")).toBe(handoff);
  await expect(page.getByRole("heading", { name: "Review saved estimate for invoicing" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Review approved invoice lines" })).toBeEnabled();
  const beforePreparation = (await readBilling()).packages.length;
  const firstCorrection = await correctEstimateCustomer("Synthetic Customer Corrected");
  await rejectStaleReview("Review approved invoice lines");
  expect((await readBilling()).packages).toHaveLength(beforePreparation);
  await expect(page).toHaveURL(url => url.searchParams.get("documentId") === firstCorrection.documentId);
  const earlierReview = page.url();
  await page.getByRole("button", { name: "Review approved invoice lines" }).click();
  await expect(page.getByRole("heading", { name: "Review final invoice" })).toBeVisible();
  await expect(page.getByRole("region", { name: "Invoice review" })).toContainText("$143.50");
  const finalCorrection = await correctEstimateCustomer("Synthetic Customer Final");
  await rejectStaleReview("Issue invoice");
  await expect(page).toHaveURL(url => url.searchParams.get("documentId") === finalCorrection.documentId);
  const finalReview = page.url();
  await page.getByRole("button", { name: "Review approved invoice lines" }).click();
  await expect(page.getByRole("region", { name: "Invoice review" })).toContainText("Synthetic Customer Final");
  await expect(page.getByRole("button", { name: "Receive payment" })).toHaveCount(0);
  await page.getByRole("button", { name: "Issue invoice", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Final service invoice" })).toBeVisible({ timeout: 20_000 });
  await expect(page.getByRole("button", { name: "Print", exact: true })).toBeVisible();
  const invoice = (await (await page.request.get(billingUrl)).json()).invoices[0];
  expect(invoice).toMatchObject({ status: "POSTED", totalCents: 14350, ledger: { estimateId: fixture.estimateId, estimateDocument: finalCorrection }, entries: [] });
  await page.goto(earlierReview);
  await expect(page.getByRole("link", { name: "Open / Print Final Invoice" })).toHaveAttribute("href", new RegExp(`sourceId=${invoice.id}`));
  await expect(page.getByText("This repair order already has an issued invoice.")).toBeVisible();
  await expect(page).toHaveURL(earlierReview);
  await page.getByRole("link", { name: "Open / Print Final Invoice" }).click();
  await expect(page.getByRole("heading", { name: "Final service invoice" })).toBeVisible({ timeout: 20_000 });
  await page.goto(finalReview);
  await expect(page.getByRole("heading", { name: "Final service invoice" })).toBeVisible({ timeout: 20_000 });
  await page.reload();
  await expect(page.getByRole("heading", { name: "Final service invoice" })).toBeVisible({ timeout: 20_000 });
  await page.getByRole("link", { name: "Return to vehicle handoff" }).click();
  await page.locator("summary").filter({ hasText: "Tools ⋮" }).click();
  await page.getByRole("navigation", { name: "Repair order tools" }).getByRole("link", { name: "Review / print invoice" }).click();
  await expect(page.getByRole("heading", { name: "Final service invoice" })).toBeVisible({ timeout: 20_000 });
  await expect(page.getByRole("button", { name: "Receive payment" })).toHaveCount(0);
  expect((await (await page.request.get(billingUrl)).json()).invoices).toHaveLength(1);
  await page.getByRole("link", { name: "Search estimates and issued invoices" }).click();
  const search = page.getByRole("textbox", { name: /Search by document number/ });
  const kind = page.getByRole("combobox", { name: "Document type" });
  await search.fill(invoice.invoiceNumber);
  await kind.selectOption("invoices");
  await page.getByRole("button", { name: "Search documents" }).click();
  await expect(page.getByRole("link", { name: `Invoice · ${invoice.invoiceNumber}` })).toBeVisible();
  await kind.selectOption("estimates");
  await page.getByRole("button", { name: "Search documents" }).click();
  await expect(page.getByText("No matching documents are available to your account.")).toBeVisible();
  const billing = await (await page.request.get(billingUrl)).json();
  await search.fill(billing.order.repairOrderNumber);
  await page.getByRole("button", { name: "Search documents" }).click();
  const correctedEstimate = page.getByRole("link", { name: `Estimate · ${billing.order.repairOrderNumber} / v1` })
    .and(page.locator(`a[href*="documentId=${finalCorrection.documentId}&"]`));
  await expect(correctedEstimate).toBeVisible();
  await expect(page.getByRole("link", { name: `Invoice · ${invoice.invoiceNumber}` })).toHaveCount(0);

  await page.request.post("/api/auth/logout");
  expect((await page.request.post("/api/auth/login", { data: { email: "jordan.sales@local.test", password: "dispatch123!" } })).ok()).toBe(true);
  expect((await page.request.get(billingUrl)).status()).toBe(403);
  await page.goto(`/service-documents?${new URLSearchParams({ kind: "invoices", query: invoice.invoiceNumber })}`);
  await expect(page.getByRole("link", { name: `Invoice · ${invoice.invoiceNumber}` })).toHaveCount(0);
});

test("an approved estimate without active repair jobs shows the recovery step", async ({ page }) => {
  if (process.env.LABOR_STAGING_CONFIRM !== "isolated") throw new Error("Use the isolated labor staging database.");
  assertLaborStagingTarget(process.env.DATABASE_URL ?? "");
  const { blockedOrderId } = JSON.parse(readFileSync("test-results/labor-staging/invoice-conversion-fixture.json", "utf-8"));
  const login = await page.request.post("/api/auth/login", { data: { email: "morgan.manager@local.test", password: "dispatch123!" } });
  expect(login.ok()).toBe(true);
  await explainSyntheticWorkdayDelay(page, "/vehicles/service-billing", "Synthetic invoice readiness verification.");
  await page.goto(`/vehicles/service-billing?repairOrderId=${blockedOrderId}`);
  await expect(page.getByRole("heading", { name: "Approved repair jobs haven’t been created" })).toBeVisible();
  await expect(page.getByRole("link", { name: "Review approved repair jobs" })).toHaveAttribute("href", `/vehicles/repair-workbench?repairOrderId=${blockedOrderId}&step=parts`);
  await expect(page.getByRole("button", { name: "Create Final Invoice" })).toHaveCount(0);
  await page.goto(`/vehicles/repair-workbench?repairOrderId=${blockedOrderId}&step=qc`);
  const draftSummary = page.getByText("Optional QC draft · does not clear invoicing", { exact: true });
  const saveDraft = page.getByRole("button", { name: "Save QC draft" });
  await expect(draftSummary).toBeVisible();
  await expect(saveDraft).toBeHidden();
  await draftSummary.click();
  for (const pass of await page.getByRole("button", { name: "Pass", exact: true }).all()) await pass.click();
  await expect(page.getByText("Draft checklist: Pass")).toBeVisible();
  await saveDraft.click();
  await expect(page.getByText("QC draft saved in this browser.")).toBeVisible();
  const billing = await page.request.get(`/api/repair-orders/${blockedOrderId}/billing`);
  const status = await billing.json();
  expect(status.readiness.mismatchCodes).toContain("INVOICE_JOB_QC_INCOMPLETE");
  expect(status.readiness.missingRepairJobLines).toEqual(["Synthetic approved repair"]);
  expect(status.invoices).toEqual([]);
});

test("the repair-job QC action clears the invoice hold and stays cleared after reload", async ({ page }) => {
  if (process.env.LABOR_STAGING_CONFIRM !== "isolated") throw new Error("Use the isolated labor staging database.");
  assertLaborStagingTarget(process.env.DATABASE_URL ?? "");
  const { qcRecoveryOrderId } = JSON.parse(readFileSync("test-results/labor-staging/invoice-conversion-fixture.json", "utf-8"));
  const login = await page.request.post("/api/auth/login", { data: { email: "morgan.manager@local.test", password: "dispatch123!" } });
  expect(login.ok()).toBe(true);
  await explainSyntheticWorkdayDelay(page, "/vehicles/service-billing", "Synthetic QC-to-invoice verification.");
  const billingUrl = `/api/repair-orders/${qcRecoveryOrderId}/billing`;
  await page.goto(`/vehicles/service-billing?repairOrderId=${qcRecoveryOrderId}`);
  await expect(page.getByRole("heading", { name: "Passed QC record missing" })).toBeVisible();
  await page.getByRole("link", { name: "Open repair job QC" }).click();
  const checklist = page.getByRole("region", { name: "Final QC checklist" });
  await expect(checklist.getByText(/J001.*Ready for inspection/)).toBeVisible();
  await checklist.getByRole("button", { name: "Save QC pass" }).click();
  await expect(checklist.getByRole("alert")).toContainText("Mark every checklist item");
  for (const pass of await checklist.getByRole("radio", { name: "Pass", exact: true }).all()) await pass.check();
  await checklist.getByRole("checkbox", { name: "Reviewed · recommendation" }).check();
  await checklist.getByLabel("Finding", { exact: true }).fill("Synthetic trim observation");
  await checklist.getByLabel("Recommended next step", { exact: true }).fill("Discuss the unrelated trim observation at handoff.");
  const recorded = page.waitForResponse(response => response.request().method() === "POST" && response.url().endsWith("/quality-inspection"));
  await checklist.getByRole("button", { name: "Save QC pass with recommendation" }).click();
  expect((await (await recorded).json()).result).toMatchObject({ disposition: "PASSED", jobStatus: "QC_PASSED" });
  const clearance = page.getByRole("region", { name: "Handoff clearance" });
  await expect(clearance).toBeVisible();
  await page.reload();
  await expect(clearance).toBeVisible();
  await expect(clearance).toContainText("Synthetic trim observation");
  const billing = await (await page.request.get(billingUrl)).json();
  expect(billing.readiness.mismatchCodes).toEqual([]);
  expect(billing.invoices).toEqual([]);
  await page.goto(`/vehicles/service-billing?repairOrderId=${qcRecoveryOrderId}`);
  await page.getByRole("button", { name: /invoice readiness|recheck invoice requirements/i }).click();
  await page.getByRole("button", { name: "Create Final Invoice" }).click();
  await expect(page.getByRole("heading", { name: "Final service invoice" })).toBeVisible();
  expect((await (await page.request.get(billingUrl)).json()).invoices).toHaveLength(1);
});
