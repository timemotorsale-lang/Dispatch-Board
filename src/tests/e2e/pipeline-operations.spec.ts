import { expect, test } from "@playwright/test";

test("pipeline captures, retains failed form entries, records next work and preserves compact views", async ({ page }) => {
  test.setTimeout(90000);
  test.skip(process.env.PIPELINE_ISOLATED_E2E !== "1", "Requires the dedicated pipeline_it_ database and fixture accounts");
  await page.route("**/api/coo-workbook/rhythm*", route => route.fulfill({ status: 503, json: { error: "Outside isolated pipeline workflow test" } }));
  await page.goto("/login");
  await page.getByLabel("Email").fill("pipeline-manager@example.test");
  await page.getByLabel("Password", { exact: true }).fill("PipelineTest123!");
  const login = page.waitForResponse(r => r.url().endsWith("/api/auth/login"));
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  expect((await login).ok()).toBe(true);
  await page.goto("/crm-next/pipeline");
  const workspace = page.getByRole("region", { name: "Pipeline operations" });
  await expect(workspace.getByRole("button", { name: "+ Lead", exact: true })).toBeEnabled();
  const name = `Browser Pipeline ${Date.now()}`;
  let failOnce = true;
  const keys: string[] = [];
  await page.route("**/api/crm-next/pipeline*", async route => {
    if (route.request().method() === "POST" && route.request().postDataJSON().action === "CAPTURE") {
      keys.push(route.request().postDataJSON().idempotencyKey);
      if (failOnce) { failOnce = false; await route.fulfill({ status: 503, json: { error: "Synthetic temporary failure. Retry this same inquiry." } }); return; }
    }
    await route.continue();
  });
  await workspace.getByRole("button", { name: "+ Lead", exact: true }).click();
  const intake = page.getByRole("dialog", { name: "Capture inquiry" });
  await intake.getByLabel("Name or inquiry description").fill(name);
  await intake.getByLabel("Phone", { exact: true }).fill("6125550199");
  await intake.getByRole("button", { name: "Capture and retain inquiry" }).click();
  await expect(intake.getByLabel("Name or inquiry description")).toHaveValue(name);
  await expect(intake.getByRole("button", { name: "Capture and retain inquiry" })).toBeEnabled();
  await intake.getByRole("button", { name: "Capture and retain inquiry" }).click();
  await expect(intake).not.toBeVisible();
  expect(keys).toHaveLength(2); expect(keys[0]).toBe(keys[1]);
  const panel = page.getByRole("complementary", { name: `Opportunity ${name}` });
  await expect(panel).toBeVisible(); await expect(panel).toContainText("Link the captured inquiry");
  await panel.getByLabel("Activity completed").selectOption({ label: "Respond to inquiry" });
  await panel.getByLabel("Short note").fill("Synthetic contact reviewed and next appointment discussed");
  await panel.getByLabel("Next action", { exact: true }).first().fill("Confirm synthetic appointment");
  const time = await page.evaluate(() => { const d = new Date(Date.now() + 90 * 60000); d.setMinutes(d.getMinutes() - d.getTimezoneOffset()); return d.toISOString().slice(0, 16); });
  await panel.getByLabel("Next action time · your local time", { exact: true }).first().fill(time);
  await panel.getByRole("button", { name: "Record outcome and next action", exact: true }).click();
  await expect(panel.getByRole("heading", { name: "Confirm synthetic appointment", exact: true })).toBeVisible();
  await panel.getByRole("button", { name: "Forecast", exact: true }).click();
  const forecast = panel.getByRole("region", { name: "Opportunity forecast" });
  await forecast.getByLabel("Forecast amount · USD").fill("30000");
  await forecast.getByLabel("Probability · percent").fill("25");
  await forecast.getByLabel("Judgment reason").fill("Synthetic evidence-based seller projection for test only");
  await forecast.getByRole("button", { name: "Save forecast judgment" }).click();
  await expect(forecast).toContainText("Seller judgment");
  await workspace.getByRole("checkbox", { name: `Select ${name}`, exact: true }).check();
  const bulk = workspace.locator("details").filter({ hasText: "Bulk tasks and handoffs" }).first();
  await bulk.locator("summary").click();
  await bulk.getByLabel("Bulk next action").fill("Review synthetic follow-up commitment");
  await bulk.getByLabel("Next action time · your local time", { exact: true }).fill(time);
  await bulk.getByLabel("Bulk reason").fill("Synthetic reviewed bulk scheduling");
  await bulk.getByRole("button", { name: "Preview selected work" }).click();
  await bulk.getByRole("button", { name: "Apply reviewed bulk work" }).click();
  await expect(workspace.getByRole("row").filter({ hasText: name })).toContainText("Review synthetic follow-up commitment");
  const download = page.waitForEvent("download");
  await workspace.getByRole("button", { name: "Export visible rows" }).click();
  expect((await download).suggestedFilename()).toBe("time-motor-sales-pipeline.csv");
  await workspace.getByRole("button", { name: "Insights", exact: true }).click();
  await expect(workspace.getByRole("region", { name: "Pipeline performance comparisons" })).toContainText("Mean first response");
  await workspace.getByRole("button", { name: "Pipeline", exact: true }).click();
  await workspace.getByRole("button", { name: "Board", exact: true }).click();
  await expect(workspace.getByRole("button", { name: new RegExp(name) }).first()).toBeVisible();
  await workspace.getByRole("button", { name: "List", exact: true }).click();
  await workspace.getByRole("combobox", { name: "Period", exact: true }).selectOption("last_month");
  await workspace.getByRole("combobox", { name: "Date basis", exact: true }).selectOption("received");
  await expect(workspace).toContainText("America/Chicago");
  await workspace.getByRole("combobox", { name: "Work view", exact: true }).selectOption("no_activity");
  await workspace.getByRole("button", { name: "Automation", exact: true }).click();
  await expect(workspace.getByRole("heading", { name: "Internal sequences and recovery" })).toBeVisible();
  const csv = `Name,Source,Reference,Phone,Email,Vehicle\n${name} CSV good,BROWSER_CSV,${name}-good,6125550101,,Test vehicle\n${name} CSV repair,BROWSER_CSV,${name}-repair,${"9".repeat(90)},,Test vehicle\n`;
  await workspace.getByLabel("Inquiry CSV file").setInputFiles({ name: "pipeline-inquiries.csv", mimeType: "text/csv", buffer: Buffer.from(csv) });
  await workspace.getByRole("button", { name: "Import 2 inquiries", exact: true }).click();
  const recovery = workspace.getByRole("region", { name: "Retained import recovery" });
  await expect(recovery).toBeVisible();
  await recovery.getByRole("button", { name: "Review retained rows", exact: true }).first().click();
  await recovery.getByLabel("Phone", { exact: true }).fill("6125550102");
  await recovery.getByLabel("Import correction reason").fill("Correct source phone formatting after review");
  await recovery.getByRole("button", { name: "Correct and retry retained rows" }).click();
  await expect(recovery).not.toBeVisible();
  const persisted = await (await page.request.get("/api/crm-next/pipeline")).json();
  expect(persisted.rows.filter((r: { title: string }) => r.title === `${name} CSV good`)).toHaveLength(1);
  expect(persisted.rows.filter((r: { title: string }) => r.title === `${name} CSV repair`)).toHaveLength(1);
  await workspace.getByRole("button", { name: "Run recovery and retry failed internal work" }).click();
  await expect(workspace.getByRole("status")).toContainText("Recovery processed");
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await workspace.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: "work/pipeline-browser-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1600, height: 1000 });
  await workspace.getByRole("button", { name: "Pipeline", exact: true }).click();
  await workspace.getByRole("combobox", { name: "Work view", exact: true }).selectOption("all");
  await workspace.getByRole("combobox", { name: "Period", exact: true }).selectOption("today");
  await workspace.getByRole("combobox", { name: "Date basis", exact: true }).selectOption("due");
  await page.screenshot({ path: "work/pipeline-browser-desktop.png", fullPage: true });
});
