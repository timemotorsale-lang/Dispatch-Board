import { readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";
import { assertLaborStagingTarget } from "../../../scripts/lib/labor-staging-target.mjs";
import { explainSyntheticWorkdayDelay } from "./helpers/synthetic-workday";

test.setTimeout(120_000);
test.use({ actionTimeout: 15_000 });
test.beforeAll(() => {
  if (process.env.LABOR_STAGING_CONFIRM !== "isolated" || process.env.PLAYWRIGHT_BASE_URL !== "http://127.0.0.1:3200") throw new Error("Use the isolated local labor staging runner.");
  assertLaborStagingTarget(process.env.DATABASE_URL ?? "");
});
test("native invoice, payment, frozen document, PDF and financial report with real authentication", async ({ page, request }) => {
  const fixture = JSON.parse(readFileSync("test-results/labor-staging/billing-browser-fixture.json", "utf8")) as { repairOrderId: string; packageId: string; estimateId: string };
  const billingUrl = `/api/repair-orders/${fixture.repairOrderId}/billing`;
  expect((await request.get(billingUrl)).status()).toBe(401);
  expect((await page.request.post("/api/auth/login", { data: { email: "morgan.manager@local.test", password: "dispatch123!" } })).ok()).toBe(true);
  await explainSyntheticWorkdayDelay(page, "/vehicles/service-billing", "Isolated synthetic billing verification; not starting a real operational workday.");
  await page.goto(`/vehicles/service-billing?repairOrderId=${fixture.repairOrderId}`);
  await expect(page.getByRole("heading", { name: "Service Billing", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Review final invoice", exact: true })).toBeVisible();
  await expect(page.getByRole("combobox", { name: "Invoice package", exact: true })).toHaveCount(0);
  await expect(page.getByRole("cell", { name: "$50.00", exact: true })).toBeVisible();
  await page.getByLabel("Detailed business reason").fill("Synthetic browser invoice posting verification");
  await page.getByRole("button", { name: "Create Final Invoice", exact: true }).click();
  await expect(page.getByText(/Open balance \$143.50/)).toBeVisible();
  await expect(page.getByRole("link", { name: "Open / Print Final Invoice", exact: true })).toBeVisible();
  const invoices = await (await page.request.get(billingUrl)).json();
  const invoice = invoices.invoices[0];
  await page.getByRole("link", { name: "Open / Print Final Invoice", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Final service invoice", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Print", exact: true })).toBeVisible();
  await page.emulateMedia({ media: "print" });
  await expect(page.getByRole("navigation", { name: "Continue repair order" })).toBeHidden();
  await page.pdf({ path: "test-results/labor-staging/final-invoice.pdf", format: "Letter", printBackground: true });
  await page.emulateMedia({ media: "screen" });
  await page.getByRole("button", { name: "Record payment", exact: true }).click();
  await expect(page.getByText(/Open balance \$143.50/)).toBeVisible();
  await page.getByLabel("Amount received (USD)").fill("143.50");
  await page.getByLabel("Verified payment evidence / reference").fill(`synthetic-browser-${crypto.randomUUID()}`);
  await page.getByRole("checkbox", { name: "I verified this payment was received for this invoice.", exact: true }).check();
  await page.getByRole("button", { name: "Record payment & view receipt", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Service payment receipt", exact: true })).toBeVisible();
  const settled = await (await page.request.get(billingUrl)).json();
  expect(settled.invoices.find((item: { id: string }) => item.id === invoice.id).balance).toMatchObject({ balanceCents: 0, settlement: "SETTLED" });
  await expect(page.getByRole("img", { name: "Time Motor Sales", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Print", exact: true })).toBeVisible();
  await page.emulateMedia({ media: "print" });
  await expect(page.getByRole("navigation", { name: "Continue repair order" })).toBeHidden();
  await expect(page.getByRole("img", { name: "Time Motor Sales", exact: true })).toBeVisible();
  await page.pdf({ path: "test-results/labor-staging/payment-receipt.pdf", format: "Letter", printBackground: true });
  await page.emulateMedia({ media: "screen" });
  const documentsResponse = await page.request.get(billingUrl);
  expect(documentsResponse.headers()["cache-control"]).toContain("no-store");
  const planningBefore = await (await page.request.get(`/api/repair-orders/${fixture.repairOrderId}/planning`)).json();
  await page.goto(`/vehicles/shop-planning?repairOrderId=${fixture.repairOrderId}&estimateId=${fixture.estimateId}`);
  await expect(page.getByRole("region", { name: "Estimate saved — next step", exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "View / Print saved estimate", exact: true })).toHaveAttribute("href", `/repair-estimate?repairOrderId=${fixture.repairOrderId}&estimateId=${fixture.estimateId}`);
  const planningAfter = await (await page.request.get(`/api/repair-orders/${fixture.repairOrderId}/planning`)).json();
  expect(planningAfter.stage).toBe(planningBefore.stage);
  expect(Array.isArray(planningBefore.estimateVersions)).toBe(true);
  expect(planningAfter.estimateVersions.map((estimate: { authorizations: unknown[] }) => estimate.authorizations)).toEqual(planningBefore.estimateVersions.map((estimate: { authorizations: unknown[] }) => estimate.authorizations));
  expect(planningAfter.repairJobs).toEqual(planningBefore.repairJobs);
  await page.getByRole("link", { name: "View / Print saved estimate", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Repair Estimate" })).toBeVisible();
  await expect(page.getByRole("region", { name: "Customer and vehicle", exact: true }).getByText("Original frozen synthetic customer", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Convert to invoice", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "$50.00", exact: true })).toBeVisible();
  await page.emulateMedia({ media: "print" });
  await page.pdf({ path: "test-results/labor-staging/frozen-estimate.pdf", format: "Letter", printBackground: true });
  await page.emulateMedia({ media: "screen" });
  await page.screenshot({ path: "test-results/labor-staging/frozen-estimate.png", fullPage: true });
  await page.getByText(/^Document history ·/).click();
  await expect(page.getByRole("button", { name: /^Invoice issued ·/ })).toBeVisible();
  await expect(page.getByRole("button", { name: /^Payment received ·/ })).toBeVisible();
  const today = new Date().toISOString().slice(0, 10);
  const report = await page.request.get(`/api/reports/labor-billing?from=${today}&to=${today}`);
  expect(report.ok()).toBe(true);
  expect((await report.json()).financial).toContainEqual(expect.objectContaining({ invoice: invoice.invoiceNumber, balanceCents: 0, netPaidCents: 14350 }));
  await page.goto(`/prototype/repair-workbench?repairOrderId=${fixture.repairOrderId}&step=parts`);
  const recorded = page.getByRole("region", { name: "Already recorded", exact: true });
  await expect(recorded).toBeVisible();
  await expect(recorded).toContainText("v1 · $143.50");
  await expect(recorded).toContainText("Approved · v1");
  await expect(recorded).toContainText("1/1 jobs QC passed");
  await expect(recorded.getByRole("link", { name: "View / Print estimate", exact: true })).toHaveAttribute("href", `/repair-estimate?repairOrderId=${fixture.repairOrderId}&estimateId=${fixture.estimateId}&workflow=review`);
  await recorded.getByText("History · estimates, findings, jobs & notes", { exact: true }).click();
  await expect(recorded.getByRole("heading", { name: "Estimate revisions & decisions", exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/labor-staging/repair-recorded-work-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/labor-staging/repair-recorded-work-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  const evidenceAfterView = await (await page.request.get(`/api/repair-orders/${fixture.repairOrderId}/planning`)).json();
  expect(evidenceAfterView.stage).toBe(planningAfter.stage);
  expect(evidenceAfterView.estimateVersions).toEqual(planningAfter.estimateVersions);
  expect(evidenceAfterView.repairJobs).toEqual(planningAfter.repairJobs);
  const release = await page.request.post(`/api/repair-orders/${fixture.repairOrderId}/release-authorization`, { data: { authorizedAt: new Date().toISOString(), idempotencyKey: crypto.randomUUID(), keysVerified: true, openExceptions: [], releaseEvidence: ["Synthetic verified QC fixture and keys; not an actual vehicle release"], reason: "Synthetic isolated review workbench closeout acceptance" } });
  expect(await release.json()).toMatchObject({ result: { stage: "HANDOFF" } });
  await page.goto(`/prototype/repair-workbench?repairOrderId=${fixture.repairOrderId}`);
  await expect(page.getByRole("heading", { name: "Closeout / handoff", exact: true })).toBeVisible();
  await page.getByLabel("Receiving person / department", { exact: true }).fill("Synthetic acceptance recipient");
  await page.getByLabel("Final odometer", { exact: true }).fill("120");
  await page.getByLabel("Handoff evidence (one reference per line)", { exact: true }).fill("Synthetic handoff receipt; isolated test only");
  await page.getByRole("checkbox", { name: "Keys verified", exact: true }).check();
  await page.getByRole("checkbox", { name: "I verified the vehicle, destination and handoff evidence.", exact: true }).check();
  await page.getByRole("button", { name: "Check current handoff readiness", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Handoff readiness: READY");
  await page.getByRole("button", { name: "Close repair & record handoff", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Repair closed · handoff recorded", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Close repair & record handoff", exact: true })).toHaveCount(0);
  await page.screenshot({ path: "test-results/labor-staging/repair-workflow-closed.png", fullPage: true });
  await page.request.post("/api/auth/logout");
  expect((await page.request.post("/api/auth/login", { data: { email: "jordan.sales@local.test", password: "dispatch123!" } })).ok()).toBe(true);
  expect((await page.request.get(billingUrl)).status()).toBe(403);
  expect((await page.request.get(`/api/reports/labor-billing?from=${today}&to=${today}`)).status()).toBe(403);
});
