import { readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";
import { assertLaborStagingTarget } from "../../../scripts/lib/labor-staging-target.mjs";
import { explainSyntheticWorkdayDelay } from "./helpers/synthetic-workday";

test.setTimeout(120_000);
test.use({ actionTimeout: 15_000 });
test.beforeAll(() => {
  if (process.env.LABOR_STAGING_CONFIRM !== "isolated" || process.env.PLAYWRIGHT_BASE_URL !== "http://127.0.0.1:3200") throw new Error("Use the isolated labor staging runner.");
  assertLaborStagingTarget(process.env.DATABASE_URL ?? "");
});

test("one authenticated guide opens a quote without labor-basis paperwork and retains issued documents", async ({ page, request }) => {
  expect((await request.get("/api/settings/labor-catalog")).status()).toBe(401);
  expect((await page.request.post("/api/auth/login", { data: { email: "morgan.manager@local.test", password: "dispatch123!" } })).ok()).toBe(true);
  await explainSyntheticWorkdayDelay(page, "/diagnostics/labor-guide", "Isolated synthetic quote verification; not starting a real operational workday.");
  const fixture = JSON.parse(readFileSync("test-results/labor-staging/billing-browser-fixture.json", "utf8")) as { repairOrderId: string; estimateId: string };
  const settings = await page.request.get("/api/settings/labor-catalog");
  expect(settings.ok()).toBe(true);
  expect(settings.headers()["cache-control"]).toContain("no-store");
  const policyBefore = await settings.json();
  expect(policyBefore.allowedSystemIds).toEqual(["brakes", "steering"]);
  await page.goto(`/diagnostics/labor-guide?guide=legacy&repairOrderId=${fixture.repairOrderId}`);
  await expect(page).toHaveURL(`/prototype/repair-explorer?repairOrderId=${fixture.repairOrderId}`);
  await expect(page.getByRole("link", { name: "Legacy guide", exact: true })).toHaveCount(0);
  await expect(page.getByRole("link", { name: "New guide · Prototype", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Add Replace front pads & rotors", exact: true }).click();
  await page.getByRole("button", { name: "Review estimate", exact: true }).click();
  await page.getByLabel("Parts total for Replace front pads & rotors", { exact: true }).fill("120");
  await page.getByRole("button", { name: "Generate / Print Estimate", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Estimate worksheet", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Confirm the labor basis", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Mark manually reviewed", exact: true })).toHaveCount(0);
  await expect(page.getByLabel("Parts for Replace front pads & rotors unit price", { exact: true })).toHaveValue("120");
  const worksheet = page.getByRole("region", { name: "Guided estimate", exact: true });
  for (const price of await worksheet.locator('input[aria-label$="unit price"]').all()) await price.fill("20");
  await expect(page.getByRole("button", { name: "Generate / Print Estimate", exact: true })).toHaveAttribute("data-ready", "true");
  await page.screenshot({ path: "test-results/labor-staging/single-guide-estimate.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(`/repair-estimate?repairOrderId=${fixture.repairOrderId}&estimateId=${fixture.estimateId}&workspace=1`);
  await expect(page.getByRole("button", { name: "Print / Save PDF", exact: true })).toBeVisible();
  await expect(page.getByRole("img", { name: "Time Motor Sales", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Official repair estimate — not an authorization", exact: true })).toBeVisible();
  await page.emulateMedia({ media: "print" });
  await expect(page.getByRole("navigation", { name: "Document progress", exact: true })).toBeHidden();
  await expect(page.getByRole("img", { name: "Time Motor Sales", exact: true })).toBeVisible();
  await page.pdf({ path: "test-results/labor-staging/single-guide-estimate.pdf", format: "Letter", printBackground: true });
  await page.emulateMedia({ media: "screen" });
  expect((await (await page.request.get("/api/settings/labor-catalog")).json()).allowedSystemIds).toEqual(policyBefore.allowedSystemIds);
  await page.request.post("/api/auth/logout");
  expect((await page.request.post("/api/auth/login", { data: { email: "jordan.sales@local.test", password: "dispatch123!" } })).ok()).toBe(true);
  expect((await page.request.get("/api/settings/labor-catalog")).status()).toBe(403);
  expect((await page.request.post("/api/settings/labor-catalog", { data: { action: "CREATE_POLICY_DRAFT" } })).status()).toBe(403);
});
