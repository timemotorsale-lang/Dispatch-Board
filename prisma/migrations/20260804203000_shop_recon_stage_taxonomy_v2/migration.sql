-- Adopt Shop & Recon Stage Taxonomy v2 without discarding governed lifecycle history.
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'SHOP_ENTRY' TO 'SERVICE_RECON_JOB_INTAKE';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'CUSTODY_CHECK_IN' TO 'JOB_SCOPE_DEFINITION';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'LANE_SCOPE_CONFIRMATION' TO 'WORK_ORDER_CREATION';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'SAFETY_PRIORITY_TRIAGE' TO 'VEHICLE_INTAKE_CUSTODY';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'INSPECTION' TO 'SAFETY_MOBILITY_TRIAGE';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'FINDINGS_VERIFICATION' TO 'INSPECTION_CONCERN_VERIFICATION';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'REPAIR_PLAN_ESTIMATE' TO 'FINDINGS_REPAIR_PLAN';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'AUTHORIZATION_APPROVAL' TO 'AUTHORIZATION';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'READY_FOR_DISPATCH' TO 'DISPATCH_WORK_STAGING';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'REPAIR_EXECUTION' TO 'TECHNICIAN_COMPLETION';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'ASSIGNED_STAGED' TO 'REPAIR_EXECUTION';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'TECHNICIAN_COMPLETE' TO 'QUALITY_CONTROL_ROAD_TEST';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'QC_RELEASE_READINESS' TO 'RELEASE_HANDOVER_READINESS';
ALTER TYPE "ShopReconLifecycleStage" RENAME VALUE 'HANDOFF_SHOP_EXIT' TO 'VEHICLE_HANDOVER_SHOP_EXIT';

UPDATE "ShopReconLifecycle"
SET "zoneCode" = CASE "stage"
  WHEN 'SERVICE_RECON_JOB_INTAKE' THEN 'PRE_ARRIVAL_COORDINATION'
  WHEN 'JOB_SCOPE_DEFINITION' THEN 'PRE_ARRIVAL_COORDINATION'
  WHEN 'WORK_ORDER_CREATION' THEN 'PRE_ARRIVAL_COORDINATION'
  WHEN 'VEHICLE_INTAKE_CUSTODY' THEN 'Z02_CHECK_IN'
  WHEN 'SAFETY_MOBILITY_TRIAGE' THEN 'Z03_TRIAGE_INSPECTION'
  WHEN 'INSPECTION_CONCERN_VERIFICATION' THEN 'Z03_TRIAGE_INSPECTION'
  WHEN 'DIAGNOSIS' THEN 'Z04_DIAGNOSTIC'
  WHEN 'FINDINGS_REPAIR_PLAN' THEN 'Z05_CONTROLLED_WAIT'
  WHEN 'AUTHORIZATION' THEN 'Z05_CONTROLLED_WAIT'
  WHEN 'PARTS_RESOURCE_READINESS' THEN 'Z06_PARTS_KIT'
  WHEN 'DISPATCH_WORK_STAGING' THEN 'Z07_READY_QUEUE'
  WHEN 'REPAIR_EXECUTION' THEN 'Z08_REPAIR_BAY'
  WHEN 'TECHNICIAN_COMPLETION' THEN 'Z10_QC'
  WHEN 'QUALITY_CONTROL_ROAD_TEST' THEN 'Z10_QC'
  WHEN 'RELEASE_HANDOVER_READINESS' THEN 'Z11_OUTBOUND'
  WHEN 'VEHICLE_HANDOVER_SHOP_EXIT' THEN 'Z11_OUTBOUND'
END,
"nextAction" = CASE "stage"
  WHEN 'SERVICE_RECON_JOB_INTAKE' THEN 'Complete the controlled Service / Recon job intake.'
  WHEN 'JOB_SCOPE_DEFINITION' THEN 'Define and freeze the exact requested Shop scope.'
  WHEN 'WORK_ORDER_CREATION' THEN 'Create the controlled work order linked to the scope.'
  WHEN 'VEHICLE_INTAKE_CUSTODY' THEN 'Match the vehicle and accept accountable custody.'
  WHEN 'SAFETY_MOBILITY_TRIAGE' THEN 'Complete safety and mobility triage.'
  WHEN 'INSPECTION_CONCERN_VERIFICATION' THEN 'Inspect the vehicle and verify the concern.'
  WHEN 'DIAGNOSIS' THEN 'Complete supported diagnosis and proposed correction.'
  WHEN 'FINDINGS_REPAIR_PLAN' THEN 'Create the versioned findings and repair plan.'
  WHEN 'AUTHORIZATION' THEN 'Record authorization for the exact current plan.'
  WHEN 'PARTS_RESOURCE_READINESS' THEN 'Prove Parts, procedure, skill and resource readiness.'
  WHEN 'DISPATCH_WORK_STAGING' THEN 'Assign and stage technician, bay, vehicle, keys and Parts.'
  WHEN 'REPAIR_EXECUTION' THEN 'Perform only the current authorized work.'
  WHEN 'TECHNICIAN_COMPLETION' THEN 'Close labor and submit technician completion evidence.'
  WHEN 'QUALITY_CONTROL_ROAD_TEST' THEN 'Complete independent QC and the required road test.'
  WHEN 'RELEASE_HANDOVER_READINESS' THEN 'Reconcile release, keys, cost, documents and receiver.'
  WHEN 'VEHICLE_HANDOVER_SHOP_EXIT' THEN 'Record accepted custody handover and Shop exit.'
END;
